'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const { createHarness, classifyCheck } = require('./foundation.cjs');
const { profile } = require('./fixtures.cjs');
const { handoff } = require('./contract-fixture.cjs');
const sha256 = v => crypto.createHash('sha256').update(v).digest('hex');
async function run() {
  const h = createHarness();
  const api = h.load('strategy-contract.md', ['fingerprint','targetFingerprint','inspectStrategy']);
  const p = profile('operations', h.blank);
  const x = handoff(p, {sha256,...api});
  assert.equal(x.schema_version, '1.1');
  const { claimEligibility } = h.load('strategy-contract.md', ['claimEligibility']);
  let sequence = 0;
  const validate = async (schema, value) => {
    const file = path.join(h.workspace, `context-${++sequence}.json`);
    fs.writeFileSync(file, JSON.stringify(value));
    return {state:classifyCheck(spawnSync('uvx',['--from','check-jsonschema==0.38.2','check-jsonschema','--schemafile',path.join(h.skillRoot,schema),file],{encoding:'utf8',windowsHide:true})),findings:[]};
  };
  const record = {id:'context:enclosures',kind:'enclosure',value:[],provenance:{kind:'user_input',reference:'fictional-interaction',observed_at:'2026-01-03T10:00:00Z',offer_span:null},confirmation:null};
  const confirmation = {application_id:'fictional-application',record_sha256:api.fingerprint(recordPayload(record),sha256),interaction_ref:'fictional-confirmation',confirmed_at:'2026-01-03T10:01:00Z'};
  record.confirmation = confirmation;
  x.application_context = {application_id:confirmation.application_id,target_sha256:x.target.sha256,records:[record]};
  const bind = value => {
    value.binding.application_id = value.application_context?.application_id ?? null;
    value.binding.application_context_sha256 = value.application_context ? sha256(JSON.stringify(value.application_context)) : null;
    value.dispositions.forEach(d => {d.binding=structuredClone(value.binding);});
    return {profile:p,binding:structuredClone(value.binding),target:structuredClone(value.target),application_context_bytes:value.application_context ? JSON.stringify(value.application_context) : null,confirmation_observations:[structuredClone(confirmation)],sha256,validate};
  };
  let host = bind(x);
  const ref = {kind:'application',application_id:confirmation.application_id,context_sha256:x.binding.application_context_sha256,record_id:record.id,pointer:'/value'};
  const c = x.claims[0]; c.subject='application'; c.evidence=[]; c.context_evidence=[ref];
  assert.equal(claimEligibility(c,x,host).state,'eligible');
  assert.equal((await api.inspectStrategy(x,host)).deterministic,'passed');
  const bad = async (mutate, schema = false) => {
    const v = structuredClone(x); mutate(v);
    const result = await api.inspectStrategy(v,host);
    assert.equal(schema ? result.schema : result.deterministic,'failed',JSON.stringify(result));
  };
  await bad(v=>{v.application_context.extra=true;},true);
  await bad(v=>{v.application_context.records[0].value=[''];},true);
  await bad(v=>{v.claims[0].context_evidence[0].pointer='/confirmation';},true);
  await bad(v=>{v.claims[0].context_evidence[0].pointer='/value/0';});
  await bad(v=>{v.claims[0].context_evidence[0].application_id='another';});
  await bad(v=>{v.claims[0].context_evidence[0].context_sha256='0'.repeat(64);});
  await bad(v=>{v.claims[0].context_evidence[0].record_id='missing';});
  await bad(v=>{v.application_context.records[0].confirmation.interaction_ref='forged';});
  await bad(v=>{v.mappings[0].evidence=[ref];},true);
  await bad(v=>{v.schema_version='9.0';},true);
  await bad(v=>{v.claims[0].subject='candidate';});
  await bad(v=>{v.claims[0].subject='mixed';});
  await bad(v=>{v.application_context.records[0].kind='recipient_address';},true);
  await bad(v=>{v.application_context.records[0].kind='application_date';v.application_context.records[0].value='2026-02-30';},true);
  await bad(v=>{v.application_context.records[0].provenance.offer_span={start:0,end:1,excerpt:'x'};},true);
  assert.equal(claimEligibility({...c,subject:'candidate'},x,host).state,'unresolved');
  assert.equal(claimEligibility({...c,subject:'mixed'},x,host).state,'unresolved');
  const original = handoff(p,{sha256,...api}).claims[0];
  assert.equal(claimEligibility({...c,subject:'mixed',evidence:original.evidence},x,host).state,'eligible');
  assert.equal(claimEligibility({...original,evidence:[{...original.evidence[0],pointer:'/candidate/name'}]},x,host).state,'invalid');
  assert.equal(claimEligibility({...c,context_evidence:[]},x,host).state,'unresolved');
  const pending=structuredClone(x); pending.application_context.records[0].confirmation=null;
  const pendingHost=bind(pending); pending.claims[0].context_evidence[0].context_sha256=pending.binding.application_context_sha256;
  pending.positioning.selected_claims=[]; pending.claims[0].realizations.forEach(r=>{r.semantic_state='unresolved';});
  assert.equal(claimEligibility(pending.claims[0],pending,pendingHost).state,'unresolved');
  assert.equal((await api.inspectStrategy(pending,pendingHost)).deterministic,'passed');
  const forged=structuredClone(x); forged.application_context.records[0].confirmation.record_sha256='0'.repeat(64);
  assert.equal((await api.inspectStrategy(forged,bind(forged))).deterministic,'failed');
  const noObservation={...host,confirmation_observations:[]};
  assert.equal(claimEligibility(c,x,noObservation).state,'invalid');
  const offerRef={kind:'offer',target_sha256:x.target.sha256,start:0,end:Array.from(x.target.text).length,excerpt:x.target.text};
  const offerClaim={...c,subject:'offer',context_evidence:[offerRef]};
  assert.equal(claimEligibility(offerClaim,x,host).state,'eligible');
  for(const patch of [{start:-1},{end:999},{excerpt:'wrong'},{target_sha256:'0'.repeat(64)}]) assert.equal(claimEligibility({...offerClaim,context_evidence:[{...offerRef,...patch}]},x,host).state,'invalid');
  assert.equal(claimEligibility(offerClaim,x,{...host,target:{kind:'role',title:'Dispatch',context:null}}).state,'invalid');
  assert.equal(claimEligibility(offerClaim,x,{...host,target:undefined}).state,'invalid');
  assert.equal(claimEligibility(c,x,{...host,application_context_bytes:host.application_context_bytes+' '}).state,'invalid');
  assert.equal(claimEligibility(c,x,{...host,binding:{...host.binding,generation:99}}).state,'invalid');
  for (const [kind,value] of [['recipient_name','Fictional Recipient'],['recipient_organization','Fictional Dispatch'],['recipient_address',['Example Lane 7','Sample City']],['application_date','2026-01-03'],['salutation','Dear Fictional Recipient'],['application_intent','I apply for the advertised role.']]) {
    const v=structuredClone(x), r=v.application_context.records[0];
    r.kind=kind;r.value=value;r.confirmation.record_sha256=api.fingerprint(recordPayload(r),sha256);
    const observed=bind(v);observed.confirmation_observations=[structuredClone(r.confirmation)];
    v.claims[0].context_evidence[0].context_sha256=v.binding.application_context_sha256;
    assert.equal((await api.inspectStrategy(v,observed)).deterministic,'passed',kind);
    if (Array.isArray(value)) assert.equal(claimEligibility({...v.claims[0],context_evidence:[{...v.claims[0].context_evidence[0],pointer:'/value/1'}]},v,observed).state,'eligible');
  }
  const selectedOffer=structuredClone(x), sr=selectedOffer.application_context.records[0];
  sr.provenance.kind='selected_offer';sr.provenance.offer_span={start:0,end:Array.from(x.target.text).length,excerpt:x.target.text};sr.confirmation=null;
  const selectedHost=bind(selectedOffer);selectedOffer.claims=[];selectedOffer.positioning.selected_claims=[];
  const {inspectApplicationContext}=h.load('strategy-contract.md',['inspectApplicationContext']);
  assert.equal(inspectApplicationContext(selectedOffer,selectedHost).length,0);
  sr.provenance.offer_span.end=999;
  assert.ok(inspectApplicationContext(selectedOffer,bind(selectedOffer)).some(f=>f.code==='context_offer_span'));
  const duplicate=structuredClone(x);duplicate.application_context.records.push(structuredClone(duplicate.application_context.records[0]));
  assert.ok(inspectApplicationContext(duplicate,bind(duplicate)).some(f=>f.code==='duplicate_context_id'));
  const empty=handoff(p,{sha256,...api});
  assert.equal((await api.inspectStrategy(empty,bind(empty))).deterministic,'passed');
  const historical = require('./contract-fixture-v1.cjs').handoff(p,{sha256,...api});
  assert.equal((await validate('schemas/application-strategy-v1.schema.json',historical)).state,'passed');
  assert.equal((await api.inspectStrategy(historical,host)).schema,'failed');
  const currentSchema=JSON.parse(fs.readFileSync(path.join(h.skillRoot,'schemas/application-strategy.schema.json'),'utf8'));
  const archiveSchema=JSON.parse(fs.readFileSync(path.join(h.skillRoot,'schemas/application-strategy-v1.schema.json'),'utf8'));
  assert.deepEqual(currentSchema.$defs.EvidenceRef,archiveSchema.$defs.EvidenceRef);
  console.log('Application context contract passed: real current/archive schemas, source eligibility, pending/forged confirmation, exact spans/pointers, canonical boundaries and null/empty context.');
}
function recordPayload({id,kind,value,provenance}) {return {id,kind,value,provenance};}
run().catch(e=>{console.error(e);process.exitCode=1;});
