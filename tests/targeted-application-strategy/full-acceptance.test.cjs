'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const api=require('./full-acceptance.cjs');
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'strategy-negative-'));
fs.writeFileSync(path.join(dir,'asset'),'fictional');
const manifest={'asset':api.hash(fs.readFileSync(path.join(dir,'asset')))};
api.verifyManifest(dir,manifest);
fs.writeFileSync(path.join(dir,'asset'),'changed');
assert.throws(()=>api.verifyManifest(dir,manifest),/hash/);
fs.unlinkSync(path.join(dir,'asset'));
assert.throws(()=>api.verifyManifest(dir,manifest),/missing/);
const full=['foundation','contracts','context','offer','evidence','questions','composition','methods','diagnostics','editorial-review','comparison','integration','semantic-acceptance','full-acceptance'].map(s=>({suite:s+'.test.cjs',exit_code:0}));
const smoke=[{suite:'integration.test.cjs',exit_code:0}];
api.checkResults(full,'full');api.checkResults(smoke,'smoke');
assert.throws(()=>api.checkResults(full.filter(r=>!['foundation.test.cjs','contracts.test.cjs','full-acceptance.test.cjs'].includes(r.suite)),'full'),/suite/);
assert.throws(()=>api.checkResults([...full,full[0]],'full'),/suite/);
assert.throws(()=>api.checkResults([...full.slice(1),{suite:'unexpected.test.cjs',exit_code:0}],'full'),/suite/);
assert.throws(()=>api.checkResults(smoke,'full'),/suite/);
assert.throws(()=>api.checkResults(full,'smoke'),/suite/);
assert.throws(()=>api.checkResults([],'smoke'),/suite/);
assert.throws(()=>api.checkResults([...smoke,...smoke],'smoke'),/suite/);
assert.throws(()=>api.checkResults([{suite:'unexpected.test.cjs',exit_code:0}],'smoke'),/suite/);
assert.throws(()=>api.checkResults(full),/mode/);
assert.throws(()=>api.checkResults(full,'automatic'),/mode/);
assert.throws(()=>api.checkResults([{...smoke[0],exit_code:1}],'smoke'),/failed/);
assert.throws(()=>api.checkResults([{...smoke[0],exit_code:null}],'smoke'),/failed/);
assert.throws(()=>api.checkCoverage([]),/coverage/);
api.checkCoverage(api.coverage);
assert.throws(()=>api.checkCoverage(api.coverage.slice(1)),/coverage/);
console.log('PASS acceptance harness rejects missing assets, byte mismatch, missing/duplicate/unexpected suites, absent/wrong modes, failed/unexecuted suites and omitted coverage; valid full and smoke inventories pass.');
