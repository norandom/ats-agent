'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');
const root = path.resolve(__dirname, '../..');
const reference = path.join(root, 'skills/targeted-cv/references/candidate-profile.md');
assert.ok(fs.existsSync(reference), 'ProfileIntake reference must exist');
const block = fs.readFileSync(reference, 'utf8').match(/```javascript\r?\n([\s\S]*?)```/);
assert.ok(block, 'executable selection/intake protocol must exist');
const { createProfileIntake } = new Function(`${block[1]}; return { createProfileIntake };`)();
const fixture = require('./fixtures/intake-reviewed.cjs');
const blank = require('../../skills/targeted-cv/templates/cv-facts.blank.json');
let checks = 0;
function check(fn) { fn(); checks++; }
async function run() {
  const base = path.join(root, 'outputs/profile-tests'); fs.mkdirSync(base, { recursive: true });
  const workspace = fs.mkdtempSync(path.join(base, 'intake-'));
  const first = path.join(workspace, 'a.json'), second = path.join(workspace, 'b.json');
  fs.writeFileSync(first, JSON.stringify(blank));
  const unrelated = structuredClone(blank); unrelated.candidate.name = 'Tovin Starbasket';
  fs.writeFileSync(second, JSON.stringify(unrelated));
  const originals = [first, second].map(p => fs.readFileSync(p));
  const reads = [];
  const host = { resolvePath: (w, p) => path.resolve(w, p), realpath: p => fs.realpathSync(p), readBytes: p => { reads.push(p); return fs.readFileSync(p); }, decodeUtf8: b => new TextDecoder('utf-8', { fatal: true }).decode(b), sha256: b => crypto.createHash('sha256').update(b).digest('hex') };
  const settings = { application_language: 'de', target_country: 'DE', offer: 'synthetic offer', output_destination: 'separate', live_document: 'separate' };
  const intake = createProfileIntake(host, settings);
  check(() => assert.equal(intake.snapshot().profile, null));
  check(() => assert.equal(reads.length, 0));
  check(() => assert.equal(intake.propose([], fixture.review).status, 'selection_required'));
  check(() => assert.equal(intake.select({ workspace_root: workspace }).status, 'selection_required'));
  check(() => assert.equal(intake.select({ workspace_root: workspace, facts_path: 'missing.json' }).status, 'input_unreadable'));
  check(() => assert.equal(intake.snapshot().profile, null));
  const a = intake.select({ workspace_root: workspace, facts_path: 'a.json' });
  check(() => assert.equal(a.selection.resolved_path, fs.realpathSync(first)));
  check(() => assert.equal(a.selection.schema_version, '2.0'));
  const token = intake.snapshot().generation;
  const proposal = intake.propose(fixture.sources, fixture.review, token);
  check(() => assert.equal(proposal.status, 'proposal'));
  check(() => assert.equal(proposal.proposed_profile.employment[0].start, '2021'));
  check(() => assert.equal(proposal.proposed_profile.employment[0].end, '2023-04'));
  check(() => assert.equal(proposal.proposed_profile.employment[0].title, null));
  check(() => assert.equal(proposal.proposed_profile.education[0].completion_status, 'in_progress'));
  check(() => assert.equal(proposal.proposed_profile.languages[0].cefr, null));
  check(() => assert.equal(proposal.proposed_profile.review_questions.length, 2));
  check(() => assert.equal(proposal.source_spans.length, 11));
  check(() => assert.equal(proposal.authorization, null));
  check(() => assert.equal(proposal.validation.semantics, 'not_assessed'));
  check(() => assert.equal(reads.length, 1)); // Hostile source never becomes a read command.
  const bad = structuredClone(fixture.review); bad.source_spans[0].quote = 'invented';
  check(() => assert.equal(intake.propose(fixture.sources, bad, token).status, 'review_required'));
  check(() => assert.equal(intake.snapshot().pending_proposal, null));
  check(() => assert.equal(intake.propose([], fixture.review, token).status, 'source_unreadable'));
  check(() => assert.equal(intake.propose(fixture.sources, null, token).status, 'review_required'));
  const unsupported = structuredClone(fixture.review); unsupported.source_spans.pop();
  unsupported.proposed_profile.languages[0].cefr = 'B2';
  check(() => assert.equal(intake.propose(fixture.sources, unsupported, token).status, 'review_required'));
  const appLeak = structuredClone(fixture.review); appLeak.proposed_profile.offer = settings.offer;
  check(() => assert.equal(intake.propose(fixture.sources, appLeak, token).status, 'review_required'));
  intake.propose(fixture.sources, fixture.review, token);
  const b = intake.select({ workspace_root: workspace, facts_path: second });
  check(() => assert.equal(b.selection.resolved_path, fs.realpathSync(second)));
  const state = intake.snapshot();
  check(() => assert.equal(state.profile.candidate.name, 'Tovin Starbasket'));
  check(() => assert.deepEqual(state.sources, []));
  check(() => assert.equal(state.pending_proposal, null));
  check(() => assert.deepEqual(state.profile.review_questions, []));
  check(() => assert.deepEqual(state.application_settings, settings));
  check(() => assert.equal(intake.propose(fixture.sources, fixture.review, token).status, 'selection_changed'));
  check(() => assert.ok(!JSON.stringify(intake.snapshot()).includes('Orla Cloudquill')));
  const secondSource = { id: 'cv-new', origin: 'explicit second candidate paste', locator: 'paste', text: 'Tovin Starbasket', unreadable_regions: [] };
  const secondReview = { proposed_profile: structuredClone(unrelated), source_spans: [{ pointer: '/candidate/name', source_id: 'cv-new', start: 0, end: secondSource.text.length, quote: 'Tovin Starbasket' }], extraction_issues: [] };
  secondReview.proposed_profile.candidate.source_ids = ['cv-new'];
  secondReview.proposed_profile.sources = [{ id: 'cv-new', type: 'candidate_supplied_cv', origin: secondSource.origin, locator: 'paste', received_at: null, as_of: null, verification: 'user_reported', verification_basis: null }];
  const secondProposal = intake.propose([secondSource], secondReview, state.generation);
  check(() => assert.equal(secondProposal.status, 'proposal'));
  check(() => assert.deepEqual(secondProposal.source_ids, ['cv-new']));
  check(() => assert.deepEqual(intake.snapshot().sources, [secondSource]));
  check(() => assert.ok(!JSON.stringify(intake.snapshot()).includes('Orla Cloudquill')));
  // Actual directory link exercises resolution to the selected destination on Windows too.
  const alias = path.join(workspace, 'alias'); fs.symlinkSync(workspace, alias, 'junction');
  check(() => assert.equal(intake.select({ workspace_root: workspace, facts_path: path.join(alias, 'a.json') }).selection.resolved_path, fs.realpathSync(first)));
  fs.unlinkSync(alias);
  const denied = createProfileIntake({ ...host, readBytes: () => { throw Error('EACCES'); } }, settings);
  check(() => assert.equal(denied.select({ workspace_root: workspace, facts_path: first }).status, 'input_unreadable'));
  check(() => assert.equal(denied.snapshot().profile, null));
  intake.select({ workspace_root: workspace, facts_path: 'missing.json' });
  check(() => assert.equal(intake.snapshot().pending_proposal, null));
  check(() => assert.deepEqual(intake.snapshot().sources, []));
  const malformed = path.join(workspace, 'malformed.json'); fs.writeFileSync(malformed, '{');
  check(() => assert.equal(intake.select({ workspace_root: workspace, facts_path: malformed }).status, 'parse_invalid'));
  check(() => assert.equal(intake.snapshot().profile, null));
  const noHash = createProfileIntake({ ...host, sha256: () => null });
  check(() => assert.equal(noHash.select({ workspace_root: workspace, facts_path: first }).status, 'check_unavailable'));
  check(() => assert.equal(noHash.snapshot().profile, null));
  const legacyFile = path.join(workspace, 'legacy.json'); fs.writeFileSync(legacyFile, JSON.stringify({ schema_version: '1.0' }));
  const legacySelection = intake.select({ workspace_root: workspace, facts_path: legacyFile });
  check(() => assert.equal(intake.propose(fixture.sources, fixture.review, legacySelection.generation).status, 'compatibility_required'));
  for (const [index, checkedProposal] of [proposal, secondProposal].entries()) {
  const proposalFile = path.join(workspace, `proposal-${index}.json`); fs.writeFileSync(proposalFile, JSON.stringify(checkedProposal.proposed_profile));
  const validation = spawnSync('uvx', ['--from', 'check-jsonschema==0.38.2', 'check-jsonschema', '--schemafile', path.join(root, 'skills/targeted-cv/schemas/cv-facts.schema.json'), proposalFile], { encoding: 'utf8', windowsHide: true, timeout: 120000 });
  check(() => assert.equal(validation.error, undefined));
  check(() => assert.equal(validation.status, 0, validation.stdout + validation.stderr));
  }
  for (const [index, file] of [first, second].entries()) check(() => assert.deepEqual(fs.readFileSync(file), originals[index]));
  console.log(`PASS intake protocol: ${checks} assertions; 2 actual uvx schema checks; host-reviewed synthetic source spans, no prose-parser claim, no canonical writes.`);
}
run().catch(error => { console.error(error); process.exitCode = 1; });
